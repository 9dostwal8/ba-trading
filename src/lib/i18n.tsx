export type TKey = keyof typeof dict;

/** Default (built-in) wording for every text key, used as fallback + admin baseline. */
export const defaultTexts = Object.fromEntries(
  Object.entries(dict as Record<string, { ar: string; ku: string }>).map(([k, v]) => [
    k,
    { ar: v.ar, ku: v.ku, en: enTexts[k] ?? v.ar },
  ]),
) as Record<string, { ar: string; ku: string; en: string }>;
export const textKeys = Object.keys(dict) as TKey[];

type Overrides = Record<string, { ar?: string | null; ku?: string | null; en?: string | null }>;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  reloadTexts: () => void;
};

const LanguageContext = createContext<Ctx>({
  lang: "ar",
  setLang: () => {},
  t: (k) => dict[k].ar,
  reloadTexts: () => {},
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");
  const [overrides, setOverrides] = useState<Overrides>({});
  const [tick, setTick] = useState(0);

  useEffect(() => {
    const stored = localStorage.getItem("lang");
    if (stored === "ku" || stored === "ar" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const { supabase } = await import("@/integrations/supabase/client");
      const { data } = await supabase.from("ui_texts").select("key, ar, ku, en");
      if (cancelled || !data) return;
      const map: Overrides = {};
      for (const row of data) map[row.key] = { ar: row.ar, ku: row.ku, en: row.en };
      setOverrides(map);
    })();
    return () => {
      cancelled = true;
    };
  }, [tick]);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "en" ? "ltr" : "rtl";
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("lang", l);
  };

  const t = (k: TKey) => {
    const custom = overrides[k]?.[lang];
    const base = lang === "en" ? enTexts[k] || dict[k].ar : dict[k][lang];
    return (custom && custom.trim()) || base;
  };

  return (
    <LanguageContext.Provider
      value={{ lang, setLang, t, reloadTexts: () => setTick((n) => n + 1) }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export const useI18n = () => useContext(LanguageContext);


export function pickName(
  row: { name_ar?: string | null; name_ku?: string | null } | null | undefined,
  lang: Lang,
) {
  if (!row) return "";
  return (lang === "ku" ? row.name_ku : row.name_ar) || row.name_ar || row.name_ku || "";
}

export function pick(ar: string | null | undefined, ku: string | null | undefined, lang: Lang) {
  return (lang === "ku" ? ku : ar) || ar || ku || "";
}

/** Admin-managed currency labels (set from store settings at runtime). */
const currencyOverride: { ar: string; ku: string } = { ar: "", ku: "" };

export function setCurrencyLabels(ar: string, ku: string) {
  currencyOverride.ar = ar;
  currencyOverride.ku = ku;
}

export function formatPrice(value: number, lang: Lang) {
  const n = new Intl.NumberFormat(lang === "en" ? "en-US" : "ar-IQ", {
    maximumFractionDigits: 0,
  }).format(value);
  const unit =
    lang === "en"
      ? enTexts['currency'] || currencyOverride.ar || dict.currency.ar
      : currencyOverride[lang] || dict.currency[lang];
  return `${n} ${unit}`;
}

/** Picks the wording for the active language from a local {ar,ku,en} label object. */
export function label(
  o: { ar?: string | null; ku?: string | null; en?: string | null },
  lang: Lang,
) {
  const v = lang === "en" ? o.en : lang === "ku" ? o.ku : o.ar;
  return (v || o.ar || o.en || o.ku || "") as string;
}

/** Discount badge text: "52%" in English, "٪52" in Arabic/Kurdish. */
export function offPct(percent: number, lang: Lang) {
  return lang === "en" ? `${percent}%` : `\u066a${percent}`;
}
